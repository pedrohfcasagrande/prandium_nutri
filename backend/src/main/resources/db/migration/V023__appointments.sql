CREATE TABLE appointments (
    id                    BIGINT AUTO_INCREMENT PRIMARY KEY,
    client_id             BIGINT       NOT NULL,
    nutritionist_id       BIGINT       NOT NULL,
    practice_id           BIGINT       NULL,
    scheduled_at          DATETIME     NOT NULL,
    duration_minutes      INT          NOT NULL DEFAULT 60,
    location              VARCHAR(20)  NOT NULL DEFAULT 'ONLINE',
    location_details      VARCHAR(500) NULL,
    notes                 VARCHAR(2000) NULL,
    status                VARCHAR(30)  NOT NULL,
    requested_by          VARCHAR(20)  NOT NULL,
    last_action_by        VARCHAR(20)  NOT NULL,
    proposed_scheduled_at DATETIME     NULL,
    proposed_by           VARCHAR(20)  NULL,
    cancel_reason         VARCHAR(500) NULL,
    canceled_at           DATETIME     NULL,
    created_at            DATETIME     NOT NULL,
    updated_at            DATETIME     NOT NULL,
    CONSTRAINT fk_appointments_client FOREIGN KEY (client_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_appointments_nutri  FOREIGN KEY (nutritionist_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_appointments_practice FOREIGN KEY (practice_id) REFERENCES nutritionist_practices (id) ON DELETE SET NULL,
    INDEX idx_appointments_client (client_id, scheduled_at),
    INDEX idx_appointments_nutri (nutritionist_id, scheduled_at),
    INDEX idx_appointments_practice (practice_id, scheduled_at),
    INDEX idx_appointments_status (status)
);
